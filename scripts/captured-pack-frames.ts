// Real 0x200 payloads, reconstructed from the 2026-09-07 Villach->Zadar ride log.
//
// PROVENANCE (docs/diagnostics-and-checks.md §11.3): GRADE A — measured. Every byte is
// a value the bus actually carried. `pack_v` and `pack_a` are the SAME-FRAME pairs, the
// subset whose two log rows share a millisecond, so a pair here is a pair the bike
// really transmitted together rather than two readings joined after the fact. The other
// four bytes (batt_temp_lo_vcu, soc, soh, batt_temp_hi_vcu) are the values in force at
// that instant, carried forward from their own rows.
//
// Re-encoded rather than captured because `rides.db` is local-only and candump captures
// under obd-garage/ are gitignored, so neither can be a `npm test` input. The encoding
// is decode-bms.ts's 0x200 read in reverse: b4-5 = BE volts x10, b6-7 = BE signed amps
// x10.
//
// ⚠️ Regenerating these means re-deriving the expected resistance with them. The check
// asserts against LOAD_WINDOW_MOHM below, which is what THIS window fits to, not a
// constant of the bike.

